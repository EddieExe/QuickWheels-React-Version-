// ── Get Translation ──
export function getTranslation(key, language = 'en') {
  const parts = key.split('.');
  let result = TRANSLATIONS;
  
  for (const part of parts) {
    if (result[part]) {
      result = result[part];
    } else {
      return key; // Return key if translation not found
    }
  }
  
  return result[language] || result['en'] || key;
}